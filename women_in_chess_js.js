/*Calculation of Pawn's starting position. Runs once on page load */

/* The following 30 lines were generated by Claude AI. This first block replaced my manual calculations of the pawn's position to automate the process and make it more robust. The second keeps the pawn's coordinates relevant to the correct textbox if the page is resized*/
window.addEventListener('load', () => {
    const boxOne = document.querySelector('.pawn_textbox[data-text="1"]');
    const container = document.querySelector('.pawn_sticky_background');
    const boxLocation = boxOne.getBoundingClientRect();
    const containerLocation = container.getBoundingClientRect();
    const pawn = document.querySelector('.pawn');

    pawn.style.transition = 'none';

    pawn.style.top = (boxLocation.top - containerLocation.top + 40) + 'px';
    pawn.style.left = (boxLocation.left - containerLocation.left - 42) + 'px';

    pawn.offsetHeight;

    pawn.style.transition = '';
});

// keeps the pawn position synced to its active box on window resize
window.addEventListener('resize', () => {
    const activePawnBox = document.querySelector('.pawn_textbox.active') || document.querySelector('.pawn_textbox[data-text="1"]');
    const containerLocation = document.querySelector('.pawn_sticky_background').getBoundingClientRect();
    const boxLocation = activePawnBox.getBoundingClientRect();
    const pawn = document.querySelector('.pawn');
    pawn.style.transition = 'none';
    pawn.style.top = (boxLocation.top - containerLocation.top + 40) + 'px';
    pawn.style.left = (boxLocation.left - containerLocation.left - 42) + 'px';
    pawn.offsetHeight;
    pawn.style.transition = '';
});

/* End of AI-generated section */

const pawn_effect = scrollama();

pawn_effect
.setup ({
    step: '.pawn_info',
    offset: 0.8,
    progress: true /* Fires 'onStepProgress' repeatedly to track how far the user has scrolled through a step and drive the opacity level of the fading-in textboxes  */
})
.onStepEnter (({ element }) => {
    const pawnStepBetweenBoxes = element.dataset.pawn; /*when a step is entered, pulls the corresponding figure from the element's data-figure attribute*/
    const pawnBox = document.querySelector(
            `.pawn_textbox[data-text="${pawnStepBetweenBoxes}"]`
        );
    const pawnBoxLocation = pawnBox.getBoundingClientRect(); /* Finds the location of each textbox */
    const pawnContainerLocation = document.querySelector('.pawn_sticky_background').getBoundingClientRect(); /*Finds the coordinates of the sticky background */
    pawnBox.classList.add('active') /* Adds active class to the appropriate textbox */

    document.querySelector('.pawn').style.top = (pawnBoxLocation.top - pawnContainerLocation.top + 40) + 'px'; /*Moves the pawn downwards (changes its vertical coordinates) to the next box, according to the coordinates of the background and the textbox. 
                                                                                                                Subtracts the background coordinates from the textbox location in order to take into account how other large
                                                                                                                objects in the document may effect the position of the current elements to get a more accurate intended position for the pawn to move to */
    document.querySelector('.pawn').style.left = (pawnBoxLocation.left - pawnContainerLocation.left - 42) + 'px'; /* Does the same as above, but handles the pawn's horizontal coordinates. The '40' and '42' are manually chosen numbers based on what looked best visually */
})

.onStepProgress(pawn_animation_progress => {
    const pawnStepBetweenBoxes = pawn_animation_progress.element.dataset.pawn; /* Selects the pawn */
    const pawnAppear = pawn_animation_progress.progress; 
    const pawnCardText = document.querySelector(`[data-text="${pawnStepBetweenBoxes}"]`); /* Selects the correct text to make it appear upon scroll */
    pawnCardText.style.opacity = pawnAppear; /*Fades in textboxes when active */
})

.onStepExit(({ element }) => {});


