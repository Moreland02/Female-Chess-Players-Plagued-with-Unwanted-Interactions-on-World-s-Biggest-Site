/* Player Introductions */
const playersScroller = scrollama(); /* Initiates scrollama for the section/function */

playersScroller
.setup({ 
    step: '.player_individual_step', /* defines the steps */
    offset: 0.5 /* defines when the step is triggered, based on how far down the screen the user scrolls */
})
.onStepEnter(({ element }) => { playerHandleStep(element); }) /* tells function to run when a step is entered */

function playerHandleStep(element) {  /* when a step is entered, pulls the corresponding figure*/
    const playerIntroStep = element.dataset.figure;
    document.querySelectorAll('[class^="player_figure"]').forEach(el => el.classList.remove('active')); /* selector for anything with the class 'player_figure' (=^) and removes their active class so that only one can be defined as active at a time, making it the visible step*/
    document.querySelector('.player_figure' + playerIntroStep).classList.add('active'); /* adds the active class to one step at a time, making it visible */
} 

